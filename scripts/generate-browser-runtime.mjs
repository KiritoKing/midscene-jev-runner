import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import process from 'node:process';
import ts from 'typescript';

const sourcePath = resolve('src/browser/snapshot.ts');
const outputPath = resolve('src/browser/snapshot-runtime.generated.ts');
const source = await readFile(sourcePath, 'utf8');
const compiled = ts
  .transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
      removeComments: true,
    },
    fileName: sourcePath,
  })
  .outputText.trim()
  .replace(/^export function browserSnapshot/u, 'function browserSnapshot');

if (!compiled.startsWith('function browserSnapshot')) {
  throw new Error('Unable to generate the browser snapshot runtime.');
}

const generated = [
  '// Generated by scripts/generate-browser-runtime.mjs. Do not edit.',
  `export const browserSnapshotSource = ${JSON.stringify(compiled)};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    throw new Error(
      'Browser snapshot runtime is stale. Run pnpm generate:browser-runtime.',
    );
  }
} else {
  await writeFile(outputPath, generated, 'utf8');
}
